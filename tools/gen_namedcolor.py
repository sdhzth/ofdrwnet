"""从 Java ofdrw 的 NamedColor.java 生成 C# 版 NamedColor.cs（一次性移植脚本）。"""
import re
import io
import os

SRC = r"E:/电子病历/ofdrw-master/ofdrw-layout/src/main/java/org/ofdrw/layout/element/canvas/NamedColor.java"
OUT = r"E:/电子病历/netofd/src/NetOfd.Layout/Element/Canvas/NamedColor.cs"

text = io.open(SRC, encoding="utf-8").read()

pattern = re.compile(r'case\s+"([a-zA-Z]+)":\s*\n\s*return\s+new\s+int\[\]\{([^}]*)\};')
items = pattern.findall(text)

entries = []
for name, nums in items:
    vals = [int(x.strip()) for x in nums.split(",")]
    if len(vals) == 3:
        entries.append((name.lower(), vals[0], vals[1], vals[2]))

print("提取颜色数:", len(entries))

L = []
A = L.append
A("using System;")
A("using System.Collections.Generic;")
A("using System.Globalization;")
A("")
A("namespace NetOfd.Layout.Element.Canvas;")
A("")
A("/// <summary>")
A("/// 颜色名称 / CSS 颜色字符串解析，返回 RGB(A) 分量。")
A("/// <para>支持：CSS 颜色名（{0} 种）、#RGB、#RRGGBB、#RRGGBBAA、rgb(r,g,b)、rgba(r,g,b,a)。</para>".format(len(entries)))
A("/// 无法解析时返回 null。")
A("/// 对应 Java: org.ofdrw.layout.element.canvas.NamedColor")
A("/// </summary>")
A("public static class NamedColor")
A("{")
A("    private static readonly Dictionary<string, int[]> Map = new(StringComparer.OrdinalIgnoreCase)")
A("    {")
for name, r, g, b in entries:
    A('        ["{0}"] = new[] {{ {1}, {2}, {3} }},'.format(name, r, g, b))
A("    };")
A("")
A("    /// <summary>解析颜色字符串为 RGB(A) 数组；长度 3 为不透明 RGB，长度 4 时末位为 Alpha(0-255)。</summary>")
A("    public static int[]? Rgb(string? hex)")
A("    {")
A("        if (string.IsNullOrWhiteSpace(hex)) return null;")
A("        hex = hex.Trim();")
A("")
A("        // CSS 颜色名")
A("        if (Map.TryGetValue(hex, out var named)) return (int[])named.Clone();")
A("")
A("        // rgb(r,g,b)")
A("        if (hex.StartsWith(\"rgb(\", StringComparison.OrdinalIgnoreCase) && hex.EndsWith(\")\", StringComparison.Ordinal))")
A("        {")
A("            var parts = hex[4..^1].Split(',');")
A("            return parts.Length == 3 && TryParseTriple(parts, out var c3) ? c3 : null;")
A("        }")
A("")
A("        // rgba(r,g,b,a)")
A("        if (hex.StartsWith(\"rgba(\", StringComparison.OrdinalIgnoreCase) && hex.EndsWith(\")\", StringComparison.Ordinal))")
A("        {")
A("            var parts = hex[5..^1].Split(',');")
A("            if (parts.Length != 4) return null;")
A("            if (!int.TryParse(parts[0].Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var r)) return null;")
A("            if (!int.TryParse(parts[1].Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var g)) return null;")
A("            if (!int.TryParse(parts[2].Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var b)) return null;")
A("            if (!double.TryParse(parts[3].Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out var a)) return null;")
A("            return new[] { r, g, b, (int)(255 * a) };")
A("        }")
A("")
A("        // #RGB / #RRGGBB / #RRGGBBAA")
A("        if (hex.StartsWith('#'))")
A("        {")
A("            var h = hex[1..];")
A("            if (h.Length == 3)")
A("                h = string.Concat(h[0], h[0], h[1], h[1], h[2], h[2]);")
A("            if (h.Length == 6")
A("                && int.TryParse(h[..2], NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var hr)")
A("                && int.TryParse(h[2..4], NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var hg)")
A("                && int.TryParse(h[4..6], NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var hb))")
A("                return new[] { hr, hg, hb };")
A("            if (h.Length == 8")
A("                && int.TryParse(h[..2], NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var hr8)")
A("                && int.TryParse(h[2..4], NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var hg8)")
A("                && int.TryParse(h[4..6], NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var hb8)")
A("                && int.TryParse(h[6..8], NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var ha8))")
A("                return new[] { hr8, hg8, hb8, ha8 };")
A("        }")
A("")
A("        // 无 # 前缀的 6 位十六进制（对齐 Java Color.decode 行为）")
A("        if (hex.Length == 6")
A("            && int.TryParse(hex[..2], NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var pr)")
A("            && int.TryParse(hex[2..4], NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var pg)")
A("            && int.TryParse(hex[4..6], NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var pb))")
A("            return new[] { pr, pg, pb };")
A("")
A("        return null;")
A("    }")
A("")
A("    private static bool TryParseTriple(string[] parts, out int[] color)")
A("    {")
A("        color = Array.Empty<int>();")
A("        if (!int.TryParse(parts[0].Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var r)) return false;")
A("        if (!int.TryParse(parts[1].Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var g)) return false;")
A("        if (!int.TryParse(parts[2].Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var b)) return false;")
A("        color = new[] { r, g, b };")
A("        return true;")
A("    }")
A("}")

with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(L) + "\n")
print("已写入:", OUT, os.path.getsize(OUT), "字节")
